-- Apply before deploying the new backend. No existing roadmap/step rows are rewritten.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
CREATE TABLE IF NOT EXISTS roadmap_graphs (
  roadmap_id BIGINT PRIMARY KEY REFERENCES roadmap(id) ON DELETE CASCADE,
  revision BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS roadmap_connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roadmap_id BIGINT NOT NULL REFERENCES roadmap(id) ON DELETE CASCADE,
  source_step_id BIGINT NOT NULL REFERENCES roadmap_steps(id) ON DELETE CASCADE,
  target_step_id BIGINT NOT NULL REFERENCES roadmap_steps(id) ON DELETE CASCADE,
  CONSTRAINT uk_roadmap_connection UNIQUE (source_step_id, target_step_id),
  CONSTRAINT ck_roadmap_connection_distinct CHECK (source_step_id <> target_step_id)
);
CREATE INDEX IF NOT EXISTS idx_roadmap_connection_roadmap ON roadmap_connections(roadmap_id);
CREATE INDEX IF NOT EXISTS idx_roadmap_connection_target ON roadmap_connections(target_step_id);
COMMIT;
